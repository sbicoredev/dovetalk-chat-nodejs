/**
 * The API contract between the Dovetalk web app and a backend.
 *
 * Conventions
 * - All timestamps are Unix epoch milliseconds (numbers).
 * - Ids are opaque strings.
 * - `senderId` and reaction ids use the same id space as `MeDto.id` and `ContactDto.id`.
 *   The special sender `"system"` marks notices such as "You created this group".
 * - Nullable fields are always present (as `null`) so clients never branch on `undefined`.
 */

export const SYSTEM_SENDER = "system";

// ---------------------------------------------------------------------------
// Auth and profile

export interface Preferences {
  enterToSend: boolean;
  previews: boolean;
  sounds: boolean;
}

export interface MeDto {
  about: string;
  avatarUrl: string | null;
  email: string;
  hue: number;
  id: string;
  name: string;
  /** As the person typed it. `null` until they add one. Other people find them by this number. */
  phone: string | null;
  preferences: Preferences;
}

export interface LoginInput {
  email: string;
  password: string;
}
export interface RegisterInput {
  email: string;
  name: string;
  password: string;
  /** Optional. Lets other people add you by number. */
  phone?: string;
}
/** Returned by login, register, guest and refresh. The refresh token travels in an httpOnly cookie. */
export interface AuthResult {
  accessToken: string;
  user: MeDto;
}

export interface UpdateMeInput {
  about?: string;
  avatarUrl?: string | null;
  name?: string;
  /** `null` removes the number. */
  phone?: string | null;
  preferences?: Partial<Preferences>;
}

// ---------------------------------------------------------------------------
// Contacts

export interface ContactDto {
  about: string;
  avatarUrl: string | null;
  blocked: boolean;
  hue: number;
  id: string;
  name: string;
  online: boolean;
  phone: string;
  /**
   * `false` for people you share a chat with but never added, or whose contact you deleted. They
   * are listed so their messages can show a name, and the address book hides them. The mock
   * server always says `true`.
   */
  saved: boolean;
}

export interface CreateContactInput {
  name: string;
  phone: string;
}
export interface UpdateContactInput {
  about?: string;
  name?: string;
  phone?: string;
}

// ---------------------------------------------------------------------------
// Messages

export type MessageKind = "text" | "voice" | "system" | "image" | "file";

export interface AttachmentDto {
  height: number | null;
  id: string;
  mime: string;
  name: string;
  size: number;
  /** Where the file can be shown or downloaded from. */
  url: string;
  width: number | null;
}

/** A short copy of the message being replied to, kept up to date by the server. */
export interface ReplyPreview {
  deleted: boolean;
  id: string;
  kind: MessageKind;
  senderId: string;
  /** Message text, the caption, or the file name. `null` once the original is deleted. */
  text: string | null;
}

export interface MessageDto {
  attachment: AttachmentDto | null;
  /** Voice messages: waveform bar heights, 0 to 100. */
  bars: number[] | null;
  chatId: string;
  /** Echo of the id the sender generated, so clients can match optimistic messages. */
  clientId: string | null;
  createdAt: number;
  deleted: boolean;
  /** Voice messages: length in seconds. */
  duration: number | null;
  edited: boolean;
  forwarded: boolean;
  id: string;
  kind: MessageKind;
  /** Emoji to the ids of the people who reacted with it. */
  reactions: Record<string, string[]>;
  replyTo: ReplyPreview | null;
  senderId: string;
  text: string | null;
}

export interface MessagePage {
  /** Oldest first. */
  items: MessageDto[];
  /** Pass as `before` to load the page of older messages. `null` when there are none. */
  nextCursor: string | null;
}

export interface MessagesQuery {
  before?: string | null;
  limit?: number;
}

export interface SendMessageInput {
  /** Required for `image` and `file`. Comes from `POST /uploads`. */
  attachmentId?: string;
  bars?: number[];
  /** Generated by the client. Sending the same id twice returns the original message. */
  clientId: string;
  duration?: number;
  kind: Exclude<MessageKind, "system">;
  replyToId?: string;
  text?: string;
}

export type DeleteScope = "me" | "everyone";

// ---------------------------------------------------------------------------
// Chats

export interface ChatDto {
  archived: boolean;
  createdAt: number;
  hue: number;
  id: string;
  lastMessage: MessageDto | null;
  /** Contact ids, not including the current user. */
  memberIds: string[];
  muted: boolean;
  /** Group name. `null` for direct chats, which use the contact's name. */
  name: string | null;
  pinned: boolean;
  type: "direct" | "group";
  unread: number;
}

export type CreateChatInput =
  | { type: "direct"; contactId: string }
  | { type: "group"; name: string; memberIds: string[] };

export interface UpdateChatInput {
  archived?: boolean;
  muted?: boolean;
  /** Groups only. */
  name?: string;
  pinned?: boolean;
}

// ---------------------------------------------------------------------------
// Status

export interface StatusDto {
  /** Index into the app's background palette. */
  color: number;
  createdAt: number;
  id: string;
  /** The current user's id or a contact id. */
  ownerId: string;
  seen: boolean;
  text: string;
}

export interface CreateStatusInput {
  color: number;
  text: string;
}

// ---------------------------------------------------------------------------
// Real-time events (socket.io)

export interface ServerEvents {
  "chat:removed": { chatId: string };
  "chat:updated": { chat: ChatDto };
  "message:new": { message: MessageDto };
  "message:updated": { message: MessageDto };
  presence: { contactId: string; online: boolean };
  "status:new": { status: StatusDto };
  typing: { chatId: string; contactId: string; name: string; isTyping: boolean };
}

export interface ClientEvents {
  typing: { chatId: string; isTyping: boolean };
}

export type ServerEventName = keyof ServerEvents;
export type ClientEventName = keyof ClientEvents;

export const SERVER_EVENT_NAMES: ServerEventName[] = [
  "message:new",
  "message:updated",
  "chat:updated",
  "chat:removed",
  "typing",
  "presence",
  "status:new",
];

export type ConnectionState = "connecting" | "connected" | "disconnected";
